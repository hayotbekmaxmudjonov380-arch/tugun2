#!/usr/bin/env python3
"""Convert a Tugun export (the claude.ai artifact database: {"path": doc, ...}) into one SQL
transaction for the new Postgres schema.

    python3 export_to_sql.py export.json migration.sql [--org-key baraka-les] [--org-name "BARAKA LES"] [--include-demo]

* Ids become deterministic uuid5 values, so running it twice yields the same ids (re-runnable on an empty db).
* The old id is kept in legacy_id.
* PINs: the old store keeps sha256("salt:pin") of 4-digit PINs. The SQL recovers each PIN inside the
  database (10^len candidates) and re-hashes it with the org's secret key, so plaintext PINs never appear
  in this file and every person keeps the same PIN.
* Login accounts are NOT migrated: claude.ai user ids do not exist in the new auth system.
  People are re-invited and linked to their staff card (see the plan).
* Demo rows (demo: true) are skipped unless --include-demo.
"""
import argparse, json, sys, uuid

NS = uuid.UUID("6f6b1b62-6b8e-4c39-9a51-7475676e0001")  # fixed namespace for Tugun


def q(v):
    """SQL literal."""
    if v is None or v == "":
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def arr(xs):
    xs = [x for x in (xs or []) if isinstance(x, str) and x.strip()]
    return "array[" + ",".join(q(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"


def uarr(xs):
    xs = [x for x in xs if x]
    return "array[" + ",".join(q(x) for x in xs) + "]::uuid[]" if xs else "'{}'::uuid[]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src"); ap.add_argument("out")
    ap.add_argument("--org-key", default="baraka-les")
    ap.add_argument("--org-name", default="BARAKA LES")
    ap.add_argument("--include-demo", action="store_true")
    a = ap.parse_args()

    docs = json.load(open(a.src, encoding="utf-8"))
    keep = lambda d: a.include_demo or not (isinstance(d, dict) and d.get("demo"))
    U = lambda kind, legacy: str(uuid.uuid5(NS, f"{a.org_key}:{kind}:{legacy}"))
    org = U("org", "")
    st = docs.get("org/structure") or {}
    branches, depts, staff = st.get("branches", {}), st.get("departments", {}), st.get("staff", {})
    settings = st.get("settings", {})
    staff = {k: v for k, v in staff.items() if v and keep(v)}
    sid = lambda legacy: U("staff", legacy) if legacy in staff else None
    positions = (docs.get("docs/lavozimlar") or {}).get("pos", {}) or {}
    positions = {k: v for k, v in positions.items() if v}

    out, counts = [], {}
    w = out.append
    def count(k, n=1): counts[k] = counts.get(k, 0) + n

    w("-- generated by export_to_sql.py; run once on an empty database as the schema owner")
    w("begin;")
    w(f"insert into public.orgs (id, name, timezone, grace_min, work_days, pin_len, max_staff) values ({q(org)}, {q(a.org_name)}, 'Asia/Tashkent', "
      f"{int(settings.get('grace', 5))}, '{{{','.join(str(int(x)) for x in settings.get('workDays', [1,2,3,4,5]))}}}', "
      f"{int(settings.get('pinLen', 4))}, {int(settings.get('maxStaff', 100))});")
    w(f"insert into private.org_secrets (org_id) values ({q(org)});")

    for k, b in branches.items():
        w(f"insert into public.branches (id, org_id, legacy_id, name, sort) values ({q(U('branch', k))}, {q(org)}, {q(k)}, {q(b.get('name') or k)}, {int(b.get('order') or 0)});"); count("branches")
    for k, d in depts.items():
        if not d or d.get("branch") not in branches: continue
        w(f"insert into public.departments (id, org_id, branch_id, legacy_id, name, sort, work_start, work_end) values ({q(U('dept', k))}, {q(org)}, {q(U('branch', d['branch']))}, "
          f"{q(k)}, {q(d.get('name') or k)}, {int(d.get('order') or 0)}, {q(d.get('workStart') or '09:00')}, {q(d.get('workEnd') or '18:00')});"); count("departments")
    dept_ok = {k for k, d in depts.items() if d and d.get("branch") in branches}

    for k, p in positions.items():
        dept = U("dept", p["deptId"]) if p.get("deptId") in dept_ok else None
        w(f"insert into public.positions (id, org_id, dept_id, legacy_id, title, reports_to, summary, duties, daily, kpi, rights, first_week, sort, version, updated_at) values ("
          f"{q(U('pos', k))}, {q(org)}, {q(dept)}, {q(k)}, {q(p.get('title') or k)}, {q(p.get('reportsTo'))}, {q(p.get('summary'))}, {arr(p.get('duties'))}, {arr(p.get('daily'))}, "
          f"{arr(p.get('kpi'))}, {arr(p.get('rights'))}, {arr(p.get('firstWeek'))}, {int(p.get('order') or 0)}, {int(p.get('v') or 1)}, coalesce({q(p.get('updatedAt'))}::timestamptz, now()));"); count("positions")

    for k, s in staff.items():
        if s.get("deptId") not in dept_ok: print(f"skip staff {k}: no department", file=sys.stderr); continue
        pos = U("pos", s["posId"]) if s.get("posId") in positions else None
        w(f"insert into public.staff (id, org_id, dept_id, position_id, legacy_id, full_name, job_title, phone, sort, is_admin) values ({q(U('staff', k))}, {q(org)}, "
          f"{q(U('dept', s['deptId']))}, {q(pos)}, {q(k)}, {q(s.get('name') or k)}, {q(s.get('role'))}, {q(s.get('phone'))}, {int(s.get('order') or 0)}, {q(s.get('access') == 'rahbar')});"); count("staff")
    staff = {k: v for k, v in staff.items() if v.get("deptId") in dept_ok}
    for k, d in depts.items():
        if k in dept_ok and d.get("headId") in staff:
            w(f"update public.departments set head_staff_id = {q(U('staff', d['headId']))} where id = {q(U('dept', k))};")

    # PINs: recover inside the database and re-hash with the org secret.
    pins = docs.get("secure/pins") or {}
    if pins.get("salt") and pins.get("pins") and (a.include_demo or not pins.get("demo")):
        n = int(pins.get("len") or settings.get("pinLen") or 4)
        w("create temp table legacy_pins (staff_id uuid, h text) on commit drop;")
        rows = [f"({q(U('staff', k))}, {q(h)})" for k, h in pins["pins"].items() if k in staff and h]
        if rows:
            w("insert into legacy_pins values " + ",\n  ".join(rows) + ";")
            w(f"insert into private.staff_pins (staff_id, org_id, pin_hash)\n"
              f"select l.staff_id, {q(org)}, app.pin_hash({q(org)}, c.pin)\n"
              f"from legacy_pins l join (select lpad(g::text, {n}, '0') pin from generate_series(0, {10**n - 1}) g) c\n"
              f"  on encode(extensions.digest({q(pins['salt'] + ':')} || c.pin, 'sha256'), 'hex') = l.h;")
            count("pins", len(rows))

    # Tasks
    task_keys = [k for k in docs if k.startswith("tasks/") and k.count("/") == 1]
    for key in task_keys:
        t = docs[key]; tk = key.split("/", 1)[1]
        if not t or not keep(t): continue
        owner = sid(t.get("ownerId"))
        if not owner:
            cand = [x for x in t.get("staffIds", []) if x in staff]
            owner = sid(cand[0]) if cand else None
        if not owner: print(f"skip task {tk}: no owner", file=sys.stderr); continue
        tid = U("task", tk)
        hist = sorted((t.get("history") or {}).items(), key=lambda kv: (kv[1] or {}).get("t", ""))
        creator = next((sid(h.get("by")) for _, h in hist if h and h.get("k") == "create"), None)
        status = t.get("status") if t.get("status") in ("new", "progress", "review", "done") else "new"
        w(f"insert into public.tasks (id, org_id, legacy_id, title, description, owner_staff_id, status, progress, start_date, due_date, done_at, created_by, created_at, updated_at, last_comment_at) values ("
          f"{q(tid)}, {q(org)}, {q(tk)}, {q((t.get('title') or 'Nomsiz')[:200])}, {q(t.get('desc'))}, {q(owner)}, {q(status)}, {max(0, min(100, int(t.get('progress') or 0)))}, "
          f"{q(t.get('start'))}, {q(t.get('due'))}, {q(t.get('doneAt'))}, {q(creator)}, coalesce({q(t.get('createdAt'))}::timestamptz, now()), "
          f"coalesce({q(t.get('updatedAt'))}::timestamptz, now()), {q(t.get('lastCommentAt'))});"); count("tasks")
        for d in dict.fromkeys(t.get("deptIds") or []):
            if d in dept_ok: w(f"insert into public.task_depts (task_id, dept_id, org_id) values ({q(tid)}, {q(U('dept', d))}, {q(org)});")
        for p in dict.fromkeys(t.get("staffIds") or []):
            if p in staff: w(f"insert into public.task_staff (task_id, staff_id, org_id) values ({q(tid)}, {q(sid(p))}, {q(org)});")
        for hk, h in hist:
            if not h: continue
            w(f"insert into public.task_events (org_id, task_id, actor_staff, kind, detail, created_at) values ({q(org)}, {q(tid)}, {q(sid(h.get('by')))}, "
              f"{q(h.get('k') or 'edit')}, {q({'txt': h.get('txt', ''), 'legacy': hk})}, coalesce({q(h.get('t'))}::timestamptz, now()));"); count("task_events")
        for fk, f in (t.get("files") or {}).items():
            if not f: continue
            w(f"insert into public.task_files (org_id, task_id, storage_path, name, mime, size_bytes, uploaded_by, created_at) values ({q(org)}, {q(tid)}, "
              f"{q('legacy/' + str(f.get('id')))}, {q(f.get('name') or 'fayl')}, {q(f.get('type'))}, {q(f.get('size'))}, {q(sid(f.get('by')))}, coalesce({q(f.get('t'))}::timestamptz, now()));"); count("files")
        for ck in [k for k in docs if k.startswith(f"tasks/{tk}/comments/")]:
            c = docs[ck]
            if not c or not (c.get("text") or "").strip(): continue
            w(f"insert into public.task_comments (org_id, task_id, staff_id, body, created_at) values ({q(org)}, {q(tid)}, {q(sid(c.get('staffId')))}, "
              f"{q(c['text'][:4000])}, coalesce({q(c.get('t'))}::timestamptz, now()));"); count("comments")

    # Attendance
    for key in [k for k in docs if k.startswith("att/")]:
        day = docs[key]; dk = key.split("/", 1)[1]
        for p, r in (day.get("recs") or {}).items():
            if p not in staff or not r or not (r.get("in") or r.get("out")): continue
            src = "manual" if r.get("src") == "manual" else "kiosk"
            w(f"insert into public.attendance (org_id, staff_id, day, in_time, out_time, source) values ({q(org)}, {q(sid(p))}, {q(dk)}, {q(r.get('in'))}, {q(r.get('out'))}, {q(src)});"); count("attendance")
            for ek, e in (r.get("edits") or {}).items():
                if not e: continue
                w(f"insert into public.attendance_edits (org_id, staff_id, day, actor_staff, prev, next, reason, created_at) values ({q(org)}, {q(sid(p))}, {q(dk)}, {q(sid(e.get('by')))}, "
                  f"{q(e.get('prev') or {})}, {q(e.get('next') or {})}, {q((e.get('why') or 'eski tizimdan')[:500].ljust(3, '.'))}, coalesce({q(e.get('t'))}::timestamptz, now()));"); count("attendance_edits")

    # Charter
    nz = docs.get("docs/nizom")
    if nz:
        w(f"insert into public.charter (org_id, title, status, version, updated_at) values ({q(org)}, {q(nz.get('title') or 'Ichki nizom')}, {q(nz.get('status') or 'Loyiha')}, "
          f"{int(nz.get('v') or 1)}, coalesce({q(nz.get('updatedAt'))}::timestamptz, now()));")
        for k, s in (nz.get("sections") or {}).items():
            if not s: continue
            w(f"insert into public.charter_sections (id, org_id, legacy_id, title, body, sort) values ({q(U('sec', k))}, {q(org)}, {q(k)}, {q(s.get('title') or '')}, {q(s.get('body') or '')}, {int(s.get('order') or 0)});"); count("charter_sections")

    # Acknowledgements: trusted only when the doc key is the linked account of that staff card (same rule as today).
    for key in [k for k in docs if k.startswith("acks/")]:
        ak = key.split("/", 1)[1]; d = docs[key] or {}
        p = d.get("staffId")
        if p not in staff: continue
        trusted = (staff[p].get("userId") and ak == staff[p]["userId"]) or (a.include_demo and ak == f"demo-{p}")
        if not trusted: count("acks_skipped"); continue
        if d.get("nizom"):
            w(f"insert into public.acknowledgements (org_id, staff_id, kind, version, acked_at) values ({q(org)}, {q(sid(p))}, 'charter', {int(d['nizom'].get('v') or 1)}, coalesce({q(d['nizom'].get('t'))}::timestamptz, now()));"); count("acks")
        pa = d.get("pos") or {}
        if pa.get("id") in positions:
            w(f"insert into public.acknowledgements (org_id, staff_id, kind, position_id, version, acked_at) values ({q(org)}, {q(sid(p))}, 'position', {q(U('pos', pa['id']))}, {int(pa.get('v') or 1)}, coalesce({q(pa.get('t'))}::timestamptz, now()));"); count("acks")

    # Activity feed
    for key in [k for k in docs if k.startswith("activity/")]:
        d = docs[key] or {}
        if not keep(d): continue
        for e in (d.get("events") or {}).values():
            if not e: continue
            tk = e.get("task")
            tid = U("task", tk) if tk and f"tasks/{tk}" in docs and keep(docs[f"tasks/{tk}"]) else None
            w(f"insert into public.activity (org_id, actor_staff, kind, task_id, body, to_staff, to_depts, created_at) values ({q(org)}, {q(sid(e.get('by')))}, {q(e.get('k') or 'event')}, {q(tid)}, "
              f"{q(e.get('txt'))}, {uarr([sid(x) for x in e.get('to') or []])}, {uarr([U('dept', x) for x in e.get('dept') or [] if x in dept_ok])}, coalesce({q(e.get('t'))}::timestamptz, now()));"); count("activity")

    w("commit;")
    open(a.out, "w", encoding="utf-8").write("\n".join(out) + "\n")
    json.dump({"org_id": org, **counts}, sys.stdout, ensure_ascii=False); print()


if __name__ == "__main__":
    main()
