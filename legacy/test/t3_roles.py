"""Role-aware UI: linked xodim, linked boshliq, viewer -> sandbox simulator, no-runtime demo, mobile."""
import asyncio, copy, json, sys
sys.path.insert(0, "/home/claude/tugun/test")
from t1_owner import new_page, check, URL, OUT, SEED
from playwright.async_api import async_playwright

def seed_with(links):
    s = copy.deepcopy(SEED)
    for sid, uid in links.items():
        s["org/structure"]["staff"][sid]["userId"] = uid
    return s

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        allerrs = []
        # ---------- (a) linked xodim, Contributor
        ctx, pg, errs = await new_page(b, {"me": {"id": "u-x", "isOwner": False, "canEdit": False, "name": "Dilnoza"}}, seed=seed_with({"b2b-sales-2": "u-x"}))
        await pg.goto(URL + "#tuzilma"); await pg.wait_for_timeout(900)
        who = await pg.eval_on_selector("#whoami", "e => e.textContent")
        check("xodim: whoami shows name and role", "Dilnoza" in who and "Xodim" in who, who.replace("\n", " | "))
        check("xodim: no new-task button", not await pg.is_visible("#top-new"))
        await pg.screenshot(path=f"{OUT}/r01_xodim_board.png")
        await pg.goto(URL + "#tasklar"); await pg.wait_for_timeout(400)
        check("xodim: 'Mening tasklarim' toggle shown", await pg.is_visible('[data-action="tf-mine"]'))
        await pg.click('[data-action="tf-mine"]'); await pg.wait_for_timeout(200)
        mine = await pg.locator("table.tasks tbody tr").count()
        check("xodim: my tasks filter", mine >= 1, mine)
        n_sel = await pg.locator("table.tasks select.status-select").count()
        check("xodim: status editable only on own tasks", n_sel == mine, f"{n_sel} selects / {mine} rows")
        await pg.screenshot(path=f"{OUT}/r02_xodim_tasks.png", full_page=True)
        # open a task she executes
        tid = await pg.eval_on_selector("table.tasks tbody tr button.link", "e => e.dataset.id")
        await pg.click(f'table.tasks button.link[data-id="{tid}"]'); await pg.wait_for_timeout(400)
        dis = await pg.eval_on_selector("#f-title", "e => e.disabled")
        st_dis = await pg.eval_on_selector("#f-status", "e => e.disabled")
        check("xodim: title locked, status open", dis and not st_dis, f"title disabled={dis}, status disabled={st_dis}")
        await pg.click('[data-action="task-tab"][data-v="files"]'); await pg.wait_for_timeout(150)
        check("xodim without upload grant sees hint", "tahrirlash huquqi" in await pg.inner_text("#files-box"))
        await pg.click('[data-action="task-tab"][data-v="comments"]'); await pg.wait_for_timeout(300)
        await pg.fill("#cm-text", "Men qo'ng'iroqlarni tugatdim."); await pg.keyboard.press("Control+Enter"); await pg.wait_for_timeout(400)
        mineC = await pg.locator("#cm-list .comment.mine").count()
        check("xodim: can comment (Ctrl+Enter)", mineC == 1, mineC)
        await pg.screenshot(path=f"{OUT}/r03_xodim_modal.png")
        await pg.click('#modal [data-action="close-modal"]'); await pg.wait_for_timeout(150)
        await pg.goto(URL + "#davomat"); await pg.wait_for_timeout(400)
        check("xodim: no attendance edit buttons", await pg.locator(".clock-btn").count() == 0)
        await pg.goto(URL + "#kiosk"); await pg.wait_for_timeout(300)
        check("xodim: kiosk closed", "Terminal yopiq" in await pg.inner_text(".k-panel"))
        await pg.goto(URL + "#sozlamalar"); await pg.wait_for_timeout(300)
        check("xodim: settings read-only", await pg.locator('[data-action="new-staff"]').count() == 0)
        await pg.click("#bell"); await pg.wait_for_timeout(300)
        feed = await pg.locator("#notif .feed-item").count()
        check("xodim: feed scoped to her", feed <= 2, feed)
        await pg.screenshot(path=f"{OUT}/r04_xodim_notif.png")
        allerrs += errs; await ctx.close()
        # ---------- (b) linked boshliq (Supplies head), Contributor
        ctx, pg, errs = await new_page(b, {"me": {"id": "u-j", "isOwner": False, "canEdit": False, "name": "Jasur"}}, seed=seed_with({"b2b-supplies-1": "u-j"}))
        await pg.goto(URL + "#tasklar"); await pg.wait_for_timeout(800)
        who = await pg.eval_on_selector("#whoami", "e => e.textContent")
        check("boshliq: role shown", "boshlig" in who.lower(), who.replace("\n", " | "))
        check("boshliq: can create tasks", await pg.is_visible("#top-new"))
        await pg.click("#top-new"); await pg.wait_for_timeout(300)
        pre = await pg.eval_on_selector_all('#modal input[name="dept"]:checked', "els => els.map(e => e.value)")
        check("boshliq: own department preselected", pre == ["b2b-supplies"], pre)
        own = await pg.eval_on_selector("#f-owner", "e => e.value")
        check("boshliq: owner defaults to self", own == "b2b-supplies-1", own)
        await pg.click('#modal [data-action="close-modal"]'); await pg.wait_for_timeout(150)
        await pg.goto(URL + "#davomat"); await pg.wait_for_timeout(400)
        check("boshliq without Editor: no attendance edits", await pg.locator(".clock-btn").count() == 0)
        allerrs += errs; await ctx.close()
        # ---------- (c) viewer -> sandbox -> simulate roles
        ctx, pg, errs = await new_page(b, {"me": {"id": "u-v", "isOwner": False, "canEdit": False}, "canWrite": False})
        await pg.goto(URL + "#tuzilma"); await pg.wait_for_timeout(900)
        ban = await pg.inner_text("#banner")
        check("viewer: read-only banner with sandbox button", "faqat ko'rish" in ban, ban[:90])
        await pg.click('#banner [data-action="start-sandbox"]'); await pg.wait_for_timeout(500)
        check("sandbox: role picker shown", await pg.is_visible("#sim-role"))
        await pg.select_option("#sim-role", "xodim|b2c-sales-3"); await pg.wait_for_timeout(300)
        who = await pg.eval_on_selector("#whoami", "e => e.textContent")
        check("sandbox: simulated xodim", "Xodim" in who or "Islom" in who, who.replace("\n", " | "))
        check("sandbox xodim: no new-task", not await pg.is_visible("#top-new"))
        await pg.select_option("#sim-role", "boshliq|b2c-works-1"); await pg.wait_for_timeout(300)
        check("sandbox boshliq: new-task visible", await pg.is_visible("#top-new"))
        await pg.goto(URL + "#davomat"); await pg.wait_for_timeout(300)
        n_edit = await pg.locator(".clock-btn").count()
        check("sandbox boshliq: edits only own department", n_edit == 6, n_edit)
        await pg.screenshot(path=f"{OUT}/r05_sandbox_boshliq_att.png")
        await pg.select_option("#sim-role", "rahbar|"); await pg.wait_for_timeout(300)
        check("sandbox rahbar: all attendance editable", await pg.locator(".clock-btn").count() == 54)
        writes = await pg.evaluate("window.__writes.length")
        check("sandbox writes never reach the real db", writes == 0, writes)
        allerrs += errs; await ctx.close()
        # ---------- (d) no runtime at all -> demo sandbox, kiosk works with demo PINs
        ctx, pg, errs = await new_page(b, {"noClaude": True})
        await pg.goto(URL + "#kiosk"); await pg.wait_for_timeout(3800)
        for k in "1019": await pg.keyboard.press(k)
        await pg.wait_for_timeout(500)
        txt = await pg.inner_text(".k-panel")
        check("demo kiosk accepts demo PIN", "Xush kelibsiz" in txt or "hozirgina" in txt or "yopilgan" in txt or "Xayr" in txt, txt.replace("\n", " | ")[:100])
        allerrs += errs; await ctx.close()
        # ---------- (e) mobile
        ctx, pg, errs = await new_page(b, {}, w=390, h=844)
        await pg.goto(URL + "#tuzilma"); await pg.wait_for_timeout(900)
        await pg.screenshot(path=f"{OUT}/m01_mobile.png", full_page=False)
        await pg.click('[data-action="focus-task"][data-id="t-tom"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-action="open-task"][data-id="t-tom"]'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=f"{OUT}/m02_mobile_modal.png")
        await pg.click('#modal [data-action="close-modal"]'); await pg.wait_for_timeout(150)
        await pg.goto(URL + "#kiosk"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=f"{OUT}/m03_mobile_kiosk.png")
        await pg.goto(URL + "#davomat"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=f"{OUT}/m04_mobile_att.png")
        allerrs += errs; await ctx.close()
        await b.close()
        print("\n".join(e for e in allerrs if "ERR_FILE_NOT_FOUND" not in e) or "no console errors")

asyncio.run(main())
